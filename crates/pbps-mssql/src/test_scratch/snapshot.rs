//! What a verified re-pin reads from one SQL Server comparison database
//! (ADR-0019 §5): every managed table's rows as text cells, and the next value
//! every allocator would hand out. Only this crate supplies the SQL; the CLI
//! holds the connection, the deadline and the comparison.
//!
//! Both reads run on the apply login's connection (DEC-1165.16). A table can carry computed
//! columns and triggers, which are user code, and the apply login owns the
//! objects: it needs nothing the administrator has.

use std::collections::BTreeMap;

use pbps_db::DbError;
use pbps_db::transport::ExecuteConnection;

use super::{refused, rows_of};
use crate::ident::{literal, quote};
use crate::state::LEDGER_SCHEMA;

/// One table's rows as a multiset of text cells. A `None` cell is SQL `NULL`,
/// kept apart from the empty string.
pub struct TableRead {
    pub columns: Vec<String>,
    pub rows: BTreeMap<Vec<Option<String>>, u64>,
}

/// One allocator and the value it would hand out next. `used_by` is the
/// `schema.table.column` it fills, when exactly one column does.
pub struct AllocatorRead {
    pub name: String,
    pub used_by: Option<String>,
    pub next: String,
}

fn qualified(schema: &str, table: &str) -> Result<String, DbError> {
    Ok(format!("{}.{}", name(schema)?, name(table)?))
}

fn name(ident: &str) -> Result<String, DbError> {
    quote(ident).map_err(refused)
}

/// The text a column's value is compared as, by its base type. The conversion
/// is chosen per type because the default one loses information: `float` keeps
/// 15 digits, a date's format follows the session's language, and binary values
/// are not text at all. `None` is a type whose value cannot be compared between
/// two databases.
fn cell(column: &str, base: &str) -> Option<String> {
    let convert = |style: &str| format!("CONVERT(nvarchar(max), {column}{style})");
    Some(match base {
        "bit" | "tinyint" | "smallint" | "int" | "bigint" | "decimal" | "numeric" | "char"
        | "varchar" | "nchar" | "nvarchar" | "text" | "ntext" | "xml" => convert(""),
        "smallmoney" | "money" => convert(", 2"),
        "float" | "real" => convert(", 3"),
        "date" => convert(", 23"),
        "smalldatetime" | "datetime" | "datetime2" | "time" | "datetimeoffset" => convert(", 121"),
        "uniqueidentifier" => format!("CONVERT(nvarchar(36), {column})"),
        "binary" | "varbinary" | "image" | "hierarchyid" | "geometry" | "geography" => {
            format!("CONVERT(nvarchar(max), CONVERT(varbinary(max), {column}), 1)")
        }
        _ => return None,
    })
}

/// Reads one table's rows. The columns are sorted by name: a column added by a
/// later hop sits last in a replayed table and in declared order in a
/// bootstrapped one, and neither order is a difference in the data.
///
/// Rows are counted here, not by `GROUP BY` on the server: the default
/// collation folds case and ignores trailing spaces, and neither is allowed to
/// make two different rows one.
pub async fn read_table(
    conn: &mut impl ExecuteConnection,
    schema: &str,
    table: &str,
) -> Result<TableRead, DbError> {
    let relation = qualified(schema, table)?;
    let described = rows_of(
        conn.query(&format!(
            "SELECT c.name AS name, \
             CASE WHEN t.is_assembly_type = 1 THEN t.name ELSE b.name END AS base, \
             CONVERT(nvarchar(10), c.generated_always_type) AS generated \
             FROM sys.columns c JOIN sys.types t ON t.user_type_id = c.user_type_id \
             LEFT JOIN sys.types b ON b.user_type_id = t.system_type_id \
             WHERE c.object_id = OBJECT_ID({}) ORDER BY c.column_id",
            literal(&relation)
        ))
        .await?,
        &["name", "base", "generated"],
    )?;
    if described.is_empty() {
        // Absent is not empty: a table that cannot be found has no rows to compare.
        return Err(refused(format!(
            "{schema}.{table} has no readable columns, so its rows cannot be compared"
        )));
    }
    let mut columns = Vec::new();
    for [column, base, generated] in described.iter().map(|row| [&row[0], &row[1], &row[2]]) {
        // `timestamp` is the catalog's name for `rowversion`.
        if generated != "0" || base == "timestamp" {
            return Err(refused(format!(
                "{schema}.{table}.{column} is generated by the engine (a rowversion, a \
                 system-versioned period or a ledger column), so its value differs between \
                 any two databases and equivalence cannot be established"
            )));
        }
        let Some(text) = cell(&name(column)?, base) else {
            return Err(refused(format!(
                "{schema}.{table}.{column} has type `{base}`, whose value cannot be compared \
                 between two databases"
            )));
        };
        columns.push((column.clone(), text));
    }
    columns.sort();
    let select = columns
        .iter()
        .map(|(_, text)| text.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let mut counted = BTreeMap::new();
    for row in conn
        .query(&format!("SELECT {select} FROM {relation}"))
        .await?
    {
        let cells = (0..columns.len())
            .map(|i| Ok(row.try_get_at::<&str>(i)?.map(str::to_owned)))
            .collect::<Result<Vec<_>, DbError>>()?;
        *counted.entry(cells).or_insert(0) += 1;
    }
    Ok(TableRead {
        columns: columns.into_iter().map(|(column, _)| column).collect(),
        rows: counted,
    })
}

/// What `IDENT_CURRENT`, the column's `last_value` and its increment say.
/// `last_value` is `NULL` until a value has been generated, and `IDENT_CURRENT`
/// alone cannot tell a column reseeded to 50 that never generated one (next 50)
/// from one that did (next 51): the pair moves exactly when a value was taken.
#[derive(PartialEq)]
struct IdentityState {
    current: Option<String>,
    last: Option<String>,
    increment: Option<String>,
}

impl IdentityState {
    /// The value one allocation from this state takes: the current value of a
    /// column that never generated one, else the last plus the increment.
    fn one_step(&self) -> Option<i128> {
        let number = |text: &Option<String>| text.as_deref().and_then(|t| t.parse::<i128>().ok());
        match &self.last {
            None => number(&self.current),
            Some(_) => Some(number(&self.last)? + number(&self.increment)?),
        }
    }
}

async fn identity_state(
    conn: &mut impl ExecuteConnection,
    relation: &str,
) -> Result<IdentityState, DbError> {
    let rows = conn
        .query(&format!(
            "SELECT CONVERT(nvarchar(40), IDENT_CURRENT({lit})) AS current_value, \
             CONVERT(nvarchar(40), c.last_value) AS last_value, \
             CONVERT(nvarchar(40), IDENT_INCR({lit})) AS increment \
             FROM sys.identity_columns c WHERE c.object_id = OBJECT_ID({lit})",
            lit = literal(relation)
        ))
        .await?;
    let [row] = &rows[..] else {
        return Err(refused(format!("{relation} has no single identity column")));
    };
    let text = |column: &str| Ok::<_, DbError>(row.try_get::<&str>(column)?.map(str::to_owned));
    Ok(IdentityState {
        current: text("current_value")?,
        last: text("last_value")?,
        increment: text("increment")?,
    })
}

/// Confirms, by really using a value, that one identity column hands out what
/// its state says it will.
///
/// A failed `INSERT` still consumes an identity value, so `INSERT … DEFAULT
/// VALUES` takes one even on a table with a column that cannot be defaulted, and
/// `IDENT_CURRENT` then is the value the engine handed out. The insert runs in a
/// transaction that is rolled back: the identity value survives a rollback, and
/// the row and anything a trigger wrote do not. The probe must have moved the
/// state, and the value it took must be what one allocation takes from the state
/// read just before it; a column that cannot take another value, a failure
/// before one is generated, an `INSTEAD OF` trigger that swallows the insert, or
/// a trigger that inserts into the same table (so the last value taken is not the
/// first) each fail one of those and are refused, naming the table.
async fn identity_confirm(
    conn: &mut impl ExecuteConnection,
    schema: &str,
    table: &str,
    initial: &IdentityState,
) -> Result<(), DbError> {
    let relation = qualified(schema, table)?;
    let before = identity_state(conn, &relation).await?;
    if &before != initial {
        // An earlier probe (a trigger inserting into this table) already took
        // values here. That is the engine allocating from the state read first, so
        // it is checked as such, and probing again could only exhaust a column
        // that still has its value: a last value taken from a later probe would
        // refuse an equivalent re-pin.
        let number = |text: &Option<String>| text.as_deref().and_then(|t| t.parse::<i128>().ok());
        let (Some(first), Some(now), Some(step)) = (
            initial.one_step(),
            number(&before.current),
            number(&initial.increment),
        ) else {
            return Err(refused(format!(
                "the next value of the identity column of {schema}.{table} cannot be \
                 established: its state is unreadable"
            )));
        };
        let onward = if step > 0 { now >= first } else { now <= first };
        if onward && (now - first) % step == 0 {
            return Ok(());
        }
        return Err(refused(format!(
            "the next value of the identity column of {schema}.{table} cannot be established: \
             a probe of another table moved it in a way its state does not explain"
        )));
    }
    let probe = format!(
        "BEGIN TRANSACTION; BEGIN TRY INSERT {relation} DEFAULT VALUES; END TRY \
         BEGIN CATCH END CATCH; IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;"
    );
    if let Err(error) = conn.execute(&probe).await {
        // A batch the engine aborted can leave the transaction open.
        let _ = conn
            .execute("IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;")
            .await;
        return Err(error);
    }
    let after = identity_state(conn, &relation).await?;
    let moved = (&after.current, &after.last) != (&before.current, &before.last);
    let took = after
        .current
        .as_deref()
        .and_then(|c| c.parse::<i128>().ok());
    if !moved || took != before.one_step() {
        return Err(refused(format!(
            "the next value of the identity column of {schema}.{table} cannot be established: \
             the probe insert did not take exactly one value (a column that cannot take another \
             value, a failure before one was generated, an INSTEAD OF trigger, or a trigger that \
             inserts into the same table)"
        )));
    }
    Ok(())
}

/// Every allocator in the database: each identity column and each sequence,
/// the ledger's own tables aside (their allocator differs between a replay and
/// a bootstrap by construction). Run after every table's rows are read: a probe
/// consumes a value, and the database is discarded.
///
/// An identity column's next value is read from its state before any probe,
/// then confirmed by a probe on the state just before it. A probe can move other
/// allocators (a trigger inserting into another table, a default taking a value
/// of a sequence), and a trigger can make that depend on their state, so a probe
/// is never what an allocator is reported from; it only has to agree with the
/// state it started from. Sequences are read before any probe for the same
/// reason, and identity columns last.
pub async fn read_allocators(
    conn: &mut impl ExecuteConnection,
) -> Result<Vec<AllocatorRead>, DbError> {
    let mut found = Vec::new();
    let sequences = rows_of(
        conn.query(
            "SELECT s.name AS schema_name, q.name AS sequence_name \
             FROM sys.sequences q JOIN sys.schemas s ON s.schema_id = q.schema_id \
             WHERE q.is_ms_shipped = 0 ORDER BY s.name, q.name",
        )
        .await?,
        &["schema_name", "sequence_name"],
    )?;
    for [schema, sequence] in sequences.iter().map(|r| [&r[0], &r[1]]) {
        let relation = qualified(schema, sequence)?;
        // The column a sequence fills is the one whose default names it; a
        // sequence two columns share is compared by its own name.
        let owners = rows_of(
            conn.query(&format!(
                "SELECT DISTINCT sc.name AS schema_name, t.name AS table_name, c.name AS column_name \
                 FROM sys.sql_expression_dependencies d \
                 JOIN sys.default_constraints dc ON dc.object_id = d.referencing_id \
                 JOIN sys.tables t ON t.object_id = dc.parent_object_id \
                 JOIN sys.schemas sc ON sc.schema_id = t.schema_id \
                 JOIN sys.columns c ON c.object_id = dc.parent_object_id \
                   AND c.column_id = dc.parent_column_id \
                 WHERE d.referenced_id = OBJECT_ID({})",
                literal(&relation)
            ))
            .await?,
            &["schema_name", "table_name", "column_name"],
        )?;
        let used_by = match &owners[..] {
            [owner] => Some(format!("{}.{}.{}", owner[0], owner[1], owner[2])),
            _ => None,
        };
        let next = rows_of(
            conn.query(&format!(
                "SELECT CONVERT(nvarchar(40), NEXT VALUE FOR {relation}) AS next_value"
            ))
            .await
            .map_err(|e| {
                refused(format!(
                    "the next value of sequence {schema}.{sequence} cannot be established: {e}"
                ))
            })?,
            &["next_value"],
        )?;
        let Some(next) = next.first().and_then(|row| row.first()) else {
            return Err(refused(format!(
                "sequence {schema}.{sequence} gave no next value"
            )));
        };
        found.push(AllocatorRead {
            name: format!("{schema}.{sequence}"),
            used_by,
            next: next.clone(),
        });
    }
    // Identity columns last: a probe also evaluates the table's column defaults,
    // which can take a value of a sequence that is already read.
    let identities = rows_of(
        conn.query(&format!(
            "SELECT s.name AS schema_name, t.name AS table_name, c.name AS column_name \
             FROM sys.identity_columns c JOIN sys.tables t ON t.object_id = c.object_id \
             JOIN sys.schemas s ON s.schema_id = t.schema_id \
             WHERE t.is_ms_shipped = 0 AND NOT (s.name = {ledger} AND t.name IN ({state}, {lock})) \
             ORDER BY s.name, t.name, c.name",
            ledger = literal(LEDGER_SCHEMA),
            state = literal(pbps_db::ledger::STATE_TABLE_NAME),
            lock = literal(pbps_db::ledger::LOCK_TABLE_NAME),
        ))
        .await?,
        &["schema_name", "table_name", "column_name"],
    )?;
    let mut initial = Vec::new();
    for [schema, table, column] in identities.iter().map(|r| [&r[0], &r[1], &r[2]]) {
        let state = identity_state(conn, &qualified(schema, table)?).await?;
        let Some(next) = state.one_step() else {
            return Err(refused(format!(
                "the next value of the identity column of {schema}.{table} cannot be \
                 established: its state is unreadable"
            )));
        };
        initial.push((schema, table, column, state, next));
    }
    for (schema, table, column, state, next) in initial {
        identity_confirm(conn, schema, table, &state).await?;
        let owner = format!("{schema}.{table}.{column}");
        found.push(AllocatorRead {
            name: format!("{owner} (identity)"),
            used_by: Some(owner),
            next: next.to_string(),
        });
    }
    Ok(found)
}

