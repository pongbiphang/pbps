use super::*;

const TREE: &str = "table: app.ev\ncolumns:\n  id: {type: integer, nullable: false, identity: [1, 1]}\n  ts: {type: date, nullable: false}\npartition_by: [ts]\npartitions:\n  ev_2025: {from: [\"2025-01-01\"], to: [\"2026-01-01\"]}\n";

fn settled(d: &Demo, connection: &str) {
    succeeds(d.run(&["verify", "--db", connection]));
    let next = succeeds(d.run(&["plan", "--db", connection]));
    assert!(stdout(&next).contains("No changes"), "{}", stdout(&next));
}

#[test]
#[ignore = "needs PostgreSQL 16 and 18"]
fn partition_identity_bootstraps_verifies_and_plans_no_changes() {
    for server in [old_server(), server()] {
        let own = OwnDatabase::new(&server, "identity1681-bootstrap");
        let connection = own.connection();
        on_server(connection, "CREATE SCHEMA app");
        let d = Demo::new("identity1681-bootstrap");
        std::fs::write(d.dir.join("schema/app.ev.yml"), TREE).unwrap();
        succeeds(d.run(&["plan"]));
        d.commit();
        succeeds(d.run(&["bootstrap", "--db", connection]));
        settled(&d, connection);
        on_server(connection, "INSERT INTO app.ev(ts) VALUES ('2025-06-01')");
        assert_eq!(scalar(connection, "SELECT id::int8 FROM app.ev"), 1);
    }
}

#[test]
#[ignore = "needs PostgreSQL 16 and 18"]
fn partition_identity_pull_with_a_default_partition_round_trips() {
    for server in [old_server(), server()] {
        let source = OwnDatabase::new(&server, "identity1681-source");
        let target = OwnDatabase::new(&server, "identity1681-target");
        let (src, tgt) = (source.connection(), target.connection());
        on_server(
            src,
            "CREATE SCHEMA app;
            CREATE TABLE app.ev(id bigint GENERATED BY DEFAULT AS IDENTITY,
                at date NOT NULL, PRIMARY KEY(id, at)) PARTITION BY RANGE(at);
            CREATE TABLE app.ev_d PARTITION OF app.ev DEFAULT;
            CREATE TABLE app.shifted(gone integer, id bigint NOT NULL, at date NOT NULL);
            ALTER TABLE app.shifted DROP COLUMN gone;
            ALTER TABLE app.ev ATTACH PARTITION app.shifted
                FOR VALUES FROM ('2025-01-01') TO ('2026-01-01')",
        );
        let d = Demo::new("identity1681-pull");
        let pulled = succeeds(d.run(&["pull", "--db", src]));
        assert!(!stderr(&pulled).contains("left out"), "{}", stderr(&pulled));
        let path = d.dir.join("schema/app.ev.yml");
        let bytes = std::fs::read(&path).unwrap();
        let loaded = pbps_load::load_schema_dir(&d.dir.join("schema")).unwrap();
        assert_eq!(loaded.schema.tables.len(), 3);
        let parent = &loaded.schema.tables[&"app.ev".parse().unwrap()];
        assert!(matches!(
            parent.columns["id"].value_source,
            pbps_model::ValueSource::Identity(_)
        ));
        for name in ["app.ev_d", "app.shifted"] {
            let partition = &loaded.schema.tables[&name.parse().unwrap()];
            assert!(partition.columns.is_empty());
            assert!(partition.partition_of.as_ref().unwrap().columns.is_empty());
        }
        succeeds(d.run(&["plan"]));
        d.commit();
        on_server(tgt, "CREATE SCHEMA app");
        succeeds(d.run(&["bootstrap", "--db", tgt]));
        settled(&d, tgt);
        on_server(
            tgt,
            "INSERT INTO app.ev(at) VALUES ('2025-06-01'), ('2030-01-01')",
        );
        assert_eq!(scalar(tgt, "SELECT sum(id)::int8 FROM app.ev"), 3);
        let again = Demo::new("identity1681-pull-again");
        succeeds(again.run(&["pull", "--db", tgt]));
        assert_eq!(
            std::fs::read(again.dir.join("schema/app.ev.yml")).unwrap(),
            bytes
        );
    }
}

#[test]
#[ignore = "needs PostgreSQL 16 and 18"]
fn partition_identity_attach_accepts_plain_columns_and_refuses_own_identity() {
    for server in [old_server(), server()] {
        let own = OwnDatabase::new(&server, "identity1681-attach");
        let connection = own.connection();
        on_server(connection, "CREATE SCHEMA app");
        let d = Demo::new("identity1681-attach");
        let tree = d.dir.join("schema/app.ev.yml");
        std::fs::write(&tree, TREE).unwrap();
        let ordinary = |name: &str, identity: &str| {
            format!(
                "table: app.{name}\ncolumns:\n  id: {{type: integer, nullable: false{identity}}}\n  ts: {{type: date, nullable: false}}\n"
            )
        };
        let plain_path = d.dir.join("schema/app.plain.yml");
        let own_path = d.dir.join("schema/app.own.yml");
        let own_text = ordinary("own", ", identity: [1, 1]");
        std::fs::write(&plain_path, ordinary("plain", "")).unwrap();
        std::fs::write(&own_path, &own_text).unwrap();
        succeeds(d.run(&["plan"]));
        d.commit();
        succeeds(d.run(&["bootstrap", "--db", connection]));
        let ids = std::fs::read(d.dir.join("schema.ids.json")).unwrap();
        std::fs::remove_file(&own_path).unwrap();
        std::fs::write(
            &tree,
            format!("{TREE}  own: {{from: [\"2026-01-01\"], to: [\"2027-01-01\"]}}\n"),
        )
        .unwrap();
        let refused = d.run(&["plan"]);
        assert_ne!(code(&refused), 0);
        let said = format!("{}{}", stdout(&refused), stderr(&refused));
        assert!(
            said.contains("app.own") && said.contains("its column `id` has its own identity"),
            "{said}"
        );
        assert_eq!(std::fs::read(d.dir.join("schema.ids.json")).unwrap(), ids);
        std::fs::write(&own_path, own_text).unwrap();
        std::fs::remove_file(&plain_path).unwrap();
        std::fs::write(
            &tree,
            format!("{TREE}  plain: {{from: [\"2026-01-01\"], to: [\"2027-01-01\"]}}\n"),
        )
        .unwrap();
        succeeds(d.run(&["plan"]));
        d.commit();
        on_server(
            connection,
            "INSERT INTO app.plain VALUES (100, '2026-06-01')",
        );
        let plan = d.dir.join("attach.json");
        succeeds(d.run(&["plan", "--db", connection, "--out", plan.to_str().unwrap()]));
        succeeds(approved_apply(
            &d,
            connection,
            &plan,
            &["--allow", "constraint"],
        ));
        settled(&d, connection);
        assert_eq!(scalar(connection, "SELECT id::int8 FROM app.ev"), 100);
        on_server(connection, "INSERT INTO app.ev(ts) VALUES ('2026-07-01')");
        assert_eq!(
            scalar(
                connection,
                "SELECT id::int8 FROM app.plain WHERE ts = '2026-07-01'"
            ),
            1
        );
        // PostgreSQL 16 permits this extra sequence. Reading only the parent's
        // identity must still leave the unrepresentable tree out of a pull.
        if scalar(
            connection,
            "SELECT current_setting('server_version_num')::int8",
        ) < 180000
        {
            on_server(
                connection,
                "ALTER TABLE app.ev ATTACH PARTITION app.own
                FOR VALUES FROM ('2027-01-01') TO ('2028-01-01')",
            );
            let omitted = Demo::new("identity1681-own-sequence");
            let pulled = succeeds(omitted.run(&["pull", "--db", connection]));
            assert!(stderr(&pulled).contains("app.ev"), "{}", stderr(&pulled));
            assert!(!omitted.dir.join("schema/app.ev.yml").exists());
        }
    }
}
